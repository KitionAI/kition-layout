/**
 * `phrase` for labels that end in "…" too: a menu row that asks first (`Text Frame Options…`)
 * reads as its phrase without the ellipsis, with the ellipsis put back.
 */
export function withEllipsis(phrase: (english: string) => string) {
  return (english: string) => {
    const whole = phrase(english)
    if (whole !== english || !english.endsWith('…')) return whole
    const stem = english.slice(0, -1)
    const translated = phrase(stem)
    return translated === stem ? english : `${translated}…`
  }
}
