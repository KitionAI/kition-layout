fn row(id: &'static str, resolves: &'static str, reads: &'static str, writes: &'static str, editor: &'static [&'static str]) -> Row {
    Row { id, resolves, reads, writes, editor, provenance: "blind" }
}

pub fn rows() -> Vec<Row> {
    let mut out = small_families();
    out.extend(styles());
    out.extend(text());
    out.extend(tables());
    out
}

