type Holds = &'static [(&'static str, &'static [&'static str])];
type Setup = &'static [(&'static str, &'static str)];

const SELECT_TEXT: Setup = &[("text.select", r#"{"story":"$STORY","anchor":0,"focus":1}"#)];
const SELECT_CARET: Setup = &[("text.select", r#"{"story":"$STORY","anchor":0,"focus":0}"#)];
const SELECT_CHANGES: Setup = &[
    ("change.track", r#"{"on":true}"#),
    ("text.select", r#"{"story":"$STORY","anchor":0,"focus":0}"#),
    ("text.insert", r#"{"text":"tracked","raw":true}"#),
];
const FOOTNOTE: Setup = &[("text.select", r#"{"story":"$STORY","anchor":0,"focus":0}"#), ("footnote.insert", r#"{"text":"Note"}"#)];
const ENDNOTE: Setup = &[("text.select", r#"{"story":"$STORY","anchor":0,"focus":0}"#), ("endnote.insert", r#"{"text":"Note"}"#)];
const EDITORIAL: Setup = &[("text.select", r#"{"story":"$STORY","anchor":0,"focus":0}"#), ("note.new", r#"{"text":"Note","author":"Reader"}"#)];
const CONDITION: Setup = &[("condition.new", r#"{"name":"Flag","color":[12,34,56]}"#)];
const VARIABLE: Setup = &[("variable.define", r#"{"name":"Var","type":"custom","text":"Value"}"#)];

fn check(id: &'static str, params: &'static str, setup: Setup, required: Holds, editor: &'static [&'static str]) -> Check {
    Check { id, params, setup, required, free: &[("$B", &["name"])], editor, provenance: "blind" }
}

// These executable projections were written before opening the declarations. They probe one
// representative branch per write; the prose rows above retain the other branches. In
// particular, namespace-absence queries and external font/file inputs have no holder alias
// here and are not proven by these field probes.
pub fn checks() -> Vec<Check> {
    let mut out = text_checks();
    out.extend(style_checks());
    out.extend(table_checks());
    out.extend(small_checks());
    out
}

